# Dynamically scan verify/ to discover source files grouped by compilation
# order category. Output Make fragments use ROOT_DIR-anchored paths so
# compilation can run from isolated build directories.

to_mk_rel() { printf '%s' "../../${1#"$ROOT_DIR/"}"; }

mk_root_expr_from_rel() { printf '%s' "\$(ROOT_DIR)/${1#../../}"; }

# Helper: collect .sv files from find into a named array (bash 3.x compatible)
collect_files() {
    local _arr_name="$1"
    shift
    local -a raw_cmd=("$@")
    local -a filtered_cmd=()
    local -a find_roots=()
    local idx=0
    local f

    if [[ "${raw_cmd[0]:-}" == "find" ]]; then
        filtered_cmd+=("find")
        for ((idx = 1; idx < ${#raw_cmd[@]}; idx++)); do
            if [[ "${raw_cmd[$idx]}" == -* ]] || [[ "${raw_cmd[$idx]}" == "!" ]] || [[ "${raw_cmd[$idx]}" == "(" ]] || [[ "${raw_cmd[$idx]}" == ")" ]]; then
                break
            fi
            if [[ -e "${raw_cmd[$idx]}" ]]; then
                find_roots+=("${raw_cmd[$idx]}")
            fi
        done

        if [[ ${#find_roots[@]} -eq 0 ]]; then
            return 0
        fi

        filtered_cmd+=("${find_roots[@]}")
        for ((; idx < ${#raw_cmd[@]}; idx++)); do
            filtered_cmd+=("${raw_cmd[$idx]}")
        done
    else
        filtered_cmd=("${raw_cmd[@]}")
    fi

    while IFS= read -r -d '' f; do
        eval "${_arr_name}+=(\"$(to_mk_rel "$f")\")"
    done < <("${filtered_cmd[@]}" | sort -z)
}

from_mk_rel() {
    printf '%s' "$ROOT_DIR/${1#../../}"
}

extract_pkg_name() {
    local pkg_file="$1"
    awk '
        /^[[:space:]]*package[[:space:]]+[A-Za-z_][A-Za-z0-9_]*[[:space:]]*;/ {
            name = $2
            sub(/;.*/, "", name)
            print name
            exit
        }
    ' "$pkg_file"
}

extract_pkg_imports() {
    local pkg_file="$1"
    awk '
        /^[[:space:]]*import[[:space:]]+[A-Za-z_][A-Za-z0-9_]*::\*[[:space:]]*;/ {
            dep = $2
            sub(/::.*/, "", dep)
            if (dep != "uvm_pkg") {
                print dep
            }
        }
    ' "$pkg_file"
}

topo_sort_pkg_files() {
    local input_arr_name="$1"
    local output_arr_name="$2"
    local -a input_files=()
    local -a ordered_files=()
    local -a deps=()
    local mk_file
    local abs_file
    local pkg_name
    local dep
    local dep_key
    local dep_list
    local output_count=0
    local total_count=0
    local progress=0
    local ready=0

    eval "input_files=(\"\${${input_arr_name}[@]}\")"

    declare -A file_pkg_name=()
    declare -A pkg_name_to_file=()
    declare -A emitted_file=()
    declare -A emitted_pkg=()
    declare -A file_deps=()

    for mk_file in "${input_files[@]}"; do
        abs_file="$(from_mk_rel "$mk_file")"
        pkg_name="$(extract_pkg_name "$abs_file")"
        if [[ -z "$pkg_name" ]]; then
            echo "[ERROR] Failed to detect package name in: $abs_file" >&2
            exit 1
        fi
        if [[ -n "${pkg_name_to_file[$pkg_name]+x}" ]]; then
            echo "[ERROR] Duplicate package name '$pkg_name' in:" >&2
            echo "        ${pkg_name_to_file[$pkg_name]}" >&2
            echo "        $mk_file" >&2
            exit 1
        fi
        file_pkg_name["$mk_file"]="$pkg_name"
        pkg_name_to_file["$pkg_name"]="$mk_file"
    done

    for mk_file in "${input_files[@]}"; do
        abs_file="$(from_mk_rel "$mk_file")"
        dep_list=""
        while IFS= read -r dep; do
            if [[ -n "${pkg_name_to_file[$dep]+x}" ]]; then
                dep_key=" $dep "
                if [[ "$dep_list" != *"$dep_key"* ]]; then
                    dep_list="${dep_list}${dep} "
                fi
            fi
        done < <(extract_pkg_imports "$abs_file")
        file_deps["$mk_file"]="$dep_list"
    done

    total_count=${#input_files[@]}
    while [[ $output_count -lt $total_count ]]; do
        progress=0
        for mk_file in "${input_files[@]}"; do
            [[ -n "${emitted_file[$mk_file]+x}" ]] && continue
            ready=1
            for dep in ${file_deps[$mk_file]}; do
                if [[ -z "${emitted_pkg[$dep]+x}" ]]; then
                    ready=0
                    break
                fi
            done
            if [[ $ready -eq 1 ]]; then
                ordered_files+=("$mk_file")
                emitted_file["$mk_file"]=1
                emitted_pkg["${file_pkg_name[$mk_file]}"]=1
                output_count=$((output_count + 1))
                progress=1
            fi
        done

        if [[ $progress -eq 0 ]]; then
            echo "[ERROR] Could not resolve package compilation order." >&2
            for mk_file in "${input_files[@]}"; do
                if [[ -z "${emitted_file[$mk_file]+x}" ]]; then
                    echo "        pending: ${file_pkg_name[$mk_file]} <- ${file_deps[$mk_file]}" >&2
                fi
            done
            exit 1
        fi
    done

    eval "${output_arr_name}=()"
    for mk_file in "${ordered_files[@]}"; do
        eval "${output_arr_name}+=(\"\$mk_file\")"
    done
}

