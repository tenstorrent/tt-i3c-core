# Helper: emit a Makefile variable assignment to stdout
emit_mk_var() {
    local variable_name="$1"
    shift
    local -a items=("$@")
    local item_count=${#items[@]}
    if [[ $item_count -eq 0 ]]; then
        printf '%s :=\n' "$variable_name"
        return
    fi
    printf '%s := \\\n' "$variable_name"
    local i=0
    local item_expr=""
    for item in "${items[@]}"; do
        i=$((i + 1))
        item_expr="$(mk_root_expr_from_rel "$item")"
        if [[ $i -lt $item_count ]]; then
            printf '    %s \\\n' "$item_expr"
        else
            printf '    %s\n' "$item_expr"
        fi
    done
}

