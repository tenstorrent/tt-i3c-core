generate_rtl_filelist() {
    local output_path="$1"
    local -a rtl_non_top=()
    local -a rtl_top=()
    local -a rtl_files=()
    local rtl_file

    while IFS= read -r -d '' rtl_file; do
        case "$(basename "$rtl_file")" in
            smc_peripherals_top.sv)
                # Real I3C integration is owned by the manual rtl_i3c.f list.
                continue
                ;;
            *_top.v|*_top.sv)
                rtl_top+=("$rtl_file")
                ;;
            *)
                rtl_non_top+=("$rtl_file")
                ;;
        esac
    done < <(find "$RTL_DIR" -maxdepth 1 -type f \( -name '*.v' -o -name '*.sv' \) -print0 | sort -z)

    {
        emit_file_header "$(basename "$output_path")" "Auto-generated RTL filelist."
        printf '# Auto-generated by sim/vcs_run_script/gen_mk_files.sh\n'
        printf '# Starter RTL filelist regenerated from rtl/\n\n'
        if [[ ${#rtl_non_top[@]} -gt 0 ]]; then
            for rtl_file in "${rtl_non_top[@]}"; do
                printf '../../rtl/%s\n' "$(basename "$rtl_file")"
            done
        fi
        if [[ ${#rtl_top[@]} -gt 0 ]]; then
            for rtl_file in "${rtl_top[@]}"; do
                printf '../../rtl/%s\n' "$(basename "$rtl_file")"
            done
        fi
    } > "$output_path"
}

generate_test_filelist() {
    local output_path="$1"
    local -a test_files=()
    local -a missing_tests=()
    local test_file
    local test_name
    local existing_path="$output_path"
    local burst_light="50"
    local burst_medium="20"
    local burst_heavy="10"
    local burst_extra="1"
    local burst_plan_light="seed-major"
    local burst_plan_medium="seed-major"
    local burst_plan_heavy="seed-major"
    local burst_plan_extra="seed-major"
    local raw_line
    local line
    local comment
    local current_level=""
    local has_block_format=0
    local has_light_block=0
    local temp_path=""
    local -A assigned_tests=()

    trim_value() {
        local value="$1"
        value="${value#${value%%[![:space:]]*}}"
        value="${value%${value##*[![:space:]]}}"
        printf '%s' "$value"
    }

    apply_burst_tokens() {
        local token
        for token in "$@"; do
            case "$token" in
                light=*)
                    burst_light="${token#light=}"
                    ;;
                medium=*)
                    burst_medium="${token#medium=}"
                    ;;
                heavy=*)
                    burst_heavy="${token#heavy=}"
                    ;;
                extra=*)
                    burst_extra="${token#extra=}"
                ;;
            esac
        done
    }

    apply_burst_plan_tokens() {
        local token
        local mode
        for token in "$@"; do
            case "$token" in
                light=*|medium=*|heavy=*|extra=*)
                    mode="${token#*=}"
                    case "$mode" in
                        packed|seed-major|test-major)
                            ;;
                        *)
                            mode="seed-major"
                            ;;
                    esac
                    case "$token" in
                        light=*)
                            burst_plan_light="$mode"
                            ;;
                        medium=*)
                            burst_plan_medium="$mode"
                            ;;
                        heavy=*)
                            burst_plan_heavy="$mode"
                            ;;
                        extra=*)
                            burst_plan_extra="$mode"
                            ;;
                    esac
                    ;;
            esac
        done
    }

    normalize_group_level() {
        case "${1,,}" in
            light|lite)
                printf 'light'
                ;;
            med|medium)
                printf 'medium'
                ;;
            high|heavy)
                printf 'heavy'
                ;;
            extra)
                printf 'extra'
                ;;
            *)
                printf 'light'
                ;;
        esac
    }

    append_missing_to_light_block() {
        local source_path="$1"
        local destination_path="$2"
        local current_block=""
        local inserted=0
        local new_test
        local source_line
        local stripped_line

        : > "$destination_path"
        while IFS= read -r source_line || [[ -n "$source_line" ]]; do
            source_line="${source_line%%$'\r'}"
            stripped_line="$(trim_value "$source_line")"

            if [[ "$stripped_line" =~ ^([A-Za-z0-9_.-]+)[[:space:]]*:[[:space:]]*([A-Za-z]+)[[:space:]]+([A-Za-z]+)[[:space:]]*\{$ ]]; then
                current_block="$(normalize_group_level "${BASH_REMATCH[2]}")"
            elif [[ "$stripped_line" =~ ^(light|lite|medium|med|heavy|high|extra)[[:space:]]*=[[:space:]]*\{$ ]]; then
                current_block="$(normalize_group_level "${BASH_REMATCH[1]}")"
            elif [[ "$stripped_line" == "}" ]]; then
                if [[ "$current_block" == "light" && $inserted -eq 0 && ${#missing_tests[@]} -gt 0 ]]; then
                    for new_test in "${missing_tests[@]}"; do
                        printf '%s\n' "$new_test" >> "$destination_path"
                    done
                    inserted=1
                fi
                current_block=""
            fi

            printf '%s\n' "$source_line" >> "$destination_path"
        done < "$source_path"
    }

    if [[ -f "$existing_path" ]]; then
        local -a burst_tokens=()

        while IFS= read -r raw_line || [[ -n "$raw_line" ]]; do
            raw_line="${raw_line%%$'\r'}"
            line="$(trim_value "$raw_line")"
            [[ -z "$line" ]] && continue

            if [[ "$line" == \#* ]]; then
                comment="${line#\#}"
                comment="$(trim_value "$comment")"
                if [[ "$comment" == BURST_LIMITS* ]]; then
                    comment="${comment#BURST_LIMITS}"
                    comment="$(trim_value "$comment")"
                    read -ra burst_tokens <<< "$comment"
                    apply_burst_tokens "${burst_tokens[@]}"
                elif [[ "$comment" == BURST_PLAN* ]]; then
                    comment="${comment#BURST_PLAN}"
                    comment="$(trim_value "$comment")"
                    read -ra burst_tokens <<< "$comment"
                    apply_burst_plan_tokens "${burst_tokens[@]}"
                fi
                continue
            fi

            if [[ "$line" =~ ^([A-Za-z0-9_.-]+)[[:space:]]*:[[:space:]]*([A-Za-z]+)[[:space:]]+([A-Za-z]+)[[:space:]]*\{$ ]]; then
                current_level="$(normalize_group_level "${BASH_REMATCH[2]}")"
                has_block_format=1
                if [[ "$current_level" == "light" ]]; then
                    has_light_block=1
                fi
                continue
            fi

            if [[ "$line" =~ ^(light|lite|medium|med|heavy|high|extra)[[:space:]]*=[[:space:]]*\{$ ]]; then
                current_level="$(normalize_group_level "${BASH_REMATCH[1]}")"
                has_block_format=1
                if [[ "$current_level" == "light" ]]; then
                    has_light_block=1
                fi
                continue
            fi

            if [[ "$line" == "}" ]]; then
                current_level=""
                continue
            fi

            if [[ -n "$current_level" ]]; then
                assigned_tests["$line"]=1
            fi
        done < "$existing_path"
    fi

    while IFS= read -r -d '' test_file; do
        test_name="$(basename "$test_file" .sv)"
        case "$test_name" in
            *_base_test)
                continue
                ;;
        esac
        test_files+=("$test_name")
    done < <(find "$TEST_DIR" -type f -name '*_test.sv' -print0 | sort -z)

    for test_name in "${test_files[@]}"; do
        if [[ -z "${assigned_tests[$test_name]+x}" ]]; then
            missing_tests+=("$test_name")
        fi
    done

    if [[ -f "$existing_path" && $has_block_format -eq 1 && $has_light_block -eq 1 ]]; then
        if [[ ${#missing_tests[@]} -eq 0 ]]; then
            return 0
        fi

        temp_path="$(mktemp)"
        append_missing_to_light_block "$existing_path" "$temp_path"
        mv "$temp_path" "$output_path"
        return 0
    fi

    {
        emit_file_header "$(basename "$output_path")" "Auto-generated regression test list."
        printf '# Auto-generated by sim/vcs_run_script/gen_mk_files.sh\n'
        printf '# Starter regression test list regenerated from verify/tb/tests/\n'
        printf '# Format:\n'
        printf '# BURST_LIMITS light=%s medium=%s heavy=%s extra=%s\n' \
            "$burst_light" "$burst_medium" "$burst_heavy" "$burst_extra"
        printf '# BURST_PLAN light=%s medium=%s heavy=%s extra=%s\n' \
            "$burst_plan_light" "$burst_plan_medium" "$burst_plan_heavy" "$burst_plan_extra"
        printf '# Supported burst plan values: seed-major, packed, test-major\n'
        printf '#   seed-major = finish all selected tests for one seed before the next seed\n'
        printf '#   packed     = planner may group multiple tests/seeds in one burst for throughput\n'
        printf '#   test-major = finish one test across its seed chunks before the next test\n'
        printf '# Regression group format:\n'
        printf '#   <label> : <level> <on/off> {\n'
        printf '#   test_name\n'
        printf '# }\n'
        printf '# label must be unique. level accepts light, medium/med, heavy/high, extra.\n'
        printf '# off groups are skipped by --all and level selection.\n'
        printf '# Metadata comments are parsed; other comment lines are ignored.\n\n'
        printf 'auto : light on {\n'
        for test_name in "${test_files[@]}"; do
            printf '%s\n' "$test_name"
        done
        printf '}\n'
    } > "$output_path"
}

write_list_block() {
    local output_path="$1"
    local variable_name="$2"
    shift 2
    local -a items=("$@")

    {
        emit_file_header "$(basename "$output_path")" "Auto-generated makefile fragment."
        printf '# Auto-generated by sim/vcs_run_script/gen_mk_files.sh\n\n'
        printf '%s := \\\n' "$variable_name"
        local item_index=0
        local item_count=${#items[@]}
        for item in "${items[@]}"; do
            item_index=$((item_index + 1))
            if [[ $item_index -lt $item_count ]]; then
                printf '    %s \\\n' "$item"
            else
                printf '    %s\n' "$item"
            fi
        done
    } > "$output_path"
}

