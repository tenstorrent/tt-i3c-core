find_project_root() {
    local start_dir="$1"
    local current_dir="$start_dir"

    while [[ "$current_dir" != "/" ]]; do
        if [[ -d "$current_dir/rtl" && -d "$current_dir/sim" && -d "$current_dir/verify" ]]; then
            printf '%s\n' "$current_dir"
            return 0
        fi
        current_dir="$(dirname "$current_dir")"
    done

    return 1
}

append_incdir() {
    local dir_path="$1"
