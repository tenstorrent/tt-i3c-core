usage() {
    cat <<'EOF'
Usage: gen_mk_files.sh [OPTIONS]

Options:
    --root <project_root>  Project root to scan. If omitted, the script walks
                                                 upward from the current directory until it finds
                                                 rtl/, sim/, and verify/.
    --rtl                  Generate sim/filelists/rtl.f only.
    -t, --t, --test        Generate sim/filelists/test.f only.
    --mk                   Generate sim/mk/paths.mk, sim/mk/incdirs.mk, and
                                                 sim/mk/srcs.mk only.
    -a, --a, --all         Generate everything: mk fragments plus both filelists.
